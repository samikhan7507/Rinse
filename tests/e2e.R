# End-to-end test without a browser: drives the real server function. Run from project root: Rscript tests/e2e.R
Sys.setenv(RINSE_DB = tempfile(fileext = ".sqlite"))
suppressWarnings(try(Sys.setlocale("LC_ALL", "C.UTF-8"), silent = TRUE))
library(shiny); library(testthat)
app <- local({ source("app.R", local = TRUE)$value })
html <- function(x) paste(as.character(x$html %||% x), collapse = "")
shiny::testServer(app, {
  session$setInputs(vy_token = "")
  expect_match(html(output$root), "Welcome back")
  session$setInputs(li_email = CFG$admin_email, li_pw = "wrong", li_go = 1)
  expect_match(html(output$root), "incorrect")
  session$setInputs(li_pw = CFG$admin_password, li_go = 2)
  expect_match(html(output$root), "Administrator"); expect_match(html(output$page), "Prepare a dataset")
  session$setInputs(sample = "loan_default"); expect_match(html(output$page), "Check data readiness")
  session$setInputs(target = "defaulted", run_check = 1)
  expect_match(html(output$page), "Possible target leakage"); expect_match(html(output$page), "collection_notice_sent")
  session$setInputs(next_step = 1); expect_match(html(output$page), "Choose how to clean")
  session$setInputs(o_missing = TRUE, o_trim = TRUE, o_labels = TRUE, o_numbers = TRUE, o_dates = TRUE, o_dups = TRUE, o_const = TRUE, o_id = TRUE, o_leak = TRUE,
                    o_sparse = TRUE, o_thr = 60, o_impnum = "knn", o_impcat = "mode", o_outl = "cap", o_pii = "drop", o_flags = FALSE, run_clean = 1)
  expect_match(html(output$page), "What changed"); expect_match(html(output$page), "nearest-neighbour")
  session$setInputs(next_step = 2)
  session$setInputs(m_encode = "onehot", m_scale = "standardize", m_test = "0.2", m_seed = 42, m_strat = TRUE, m_dates = TRUE, run_ml = 1)
  expect_match(html(output$page), "Ready for modelling")
  session$setInputs(next_step = 3); expect_match(html(output$page), "Train and compare models")
  session$setInputs(mod_sel = c("Logistic regression", "Decision tree", "Random forest"), mod_cv = "3", run_models = 1)
  expect_match(html(output$page), "Did cleaning help"); expect_match(html(output$page), "ROC curves")
  session$setInputs(cm_model = "Random forest"); expect_match(html(output$cm_view), "Actual")
  session$setInputs(run_rawcmp = 1); expect_match(html(output$page), "Raw|raw")
  session$setInputs(next_step = 4); expect_match(html(output$page), "Generate insights")
  session$setInputs(run_insights = 1); expect_match(html(output$page), "Correlation map"); expect_match(html(output$page), "Unusual records")
  session$setInputs(next_step = 5); expect_match(html(output$page), "Download your results")
  for (id in c("bundle", "cleaned", "train", "test", "excel", "report", "recipe", "sqlitedb", "model", "preds")) { f <- output[[id]]; expect_true(file.exists(f) && file.size(f) > 100, info = id) }
  z <- utils::unzip(output$bundle, list = TRUE)$Name; expect_true(all(c("model.rds", "test_predictions.csv", "rinse_report.xlsx") %in% z))
  # predict page
  session$setInputs(nav = "predict"); expect_match(html(output$page), "Score a file")
  raw <- read_any("data/samples/loan_default.csv"); tf <- tempfile(fileext = ".csv"); utils::write.csv(raw[1:20, setdiff(names(raw), "defaulted")], tf, row.names = FALSE)
  session$setInputs(pred_file = list(datapath = tf, name = "new.csv"), run_pred = 1); expect_match(html(output$page), "Rows scored")
  session$setInputs(one_1 = "40", run_one = 1); expect_match(html(output$page), "Prediction")
  # drift page
  session$setInputs(nav = "drift"); expect_match(html(output$page), "Compare two datasets")
  session$setInputs(ref_src = "current", new_file = list(datapath = tf, name = "new.csv"), run_drift = 1); expect_match(html(output$page), "Shift by column")
  session$setInputs(nav = "history"); expect_match(html(output$page), "Your history")
  # admin console
  session$setInputs(nav = "admin"); expect_match(html(output$page), "Administration")
  for (t in names(ADMIN_TABS)) { session$setInputs(adm_tab = t); expect_match(html(output$page), "Administration") }
  session$setInputs(adm_tab = "overview"); expect_match(html(output$adm_overview), "Online now"); expect_match(html(output$adm_overview), "Latest sign-in attempts")
  session$setInputs(adm_tab = "database", db_table = "login_events"); expect_false(is.null(output$tbl_dbview))
  expect_match(html(output$tbl_dbsum), "Schema version")
  session$setInputs(nav = "settings"); expect_match(html(output$page), "Recent sign-ins")
  session$setInputs(st_name = "Sami A", st_save = 1); expect_match(html(output$root), "Sami A")
  session$setInputs(nav = "help"); expect_match(html(output$page), "How the score works")
  session$setInputs(logout = 1); expect_match(html(output$root), "Welcome back")
  # member cannot open admin; sign-ups are tracked
  session$setInputs(auth_tab = "signup", su_name = "Test", su_email = "t@example.com", su_pw = "Passw0rd1", su_go = 1)
  expect_match(html(output$root), "Member"); session$setInputs(nav = "admin"); expect_false(grepl("Administration", html(output$page)))
  session$setInputs(logout = 2, auth_tab = "phone"); session$setInputs(ph_num = "9876543210", ph_send = 1); expect_match(html(output$root), "Demo mode")
})
ev <- admin_login_events(); expect_true(all(c("Success", "Failed") %in% ev$result)); expect_gte(nrow(admin_models()), 3)
cat("E2E OK\n")
